test('automation rules allow only the approved four automatic WhatsApp event categories', () => {
  assert.deepEqual(Object.keys(WHATSAPP_AUTOMATION_EVENT_RULES).sort(), [
    'company_matching_digest',
    'worker_kyc_rejected',
    'worker_matching_digest',
    'worker_payment_or_plan_reminder',
  ])
  assert.equal(
    WHATSAPP_AUTOMATION_EVENT_RULES.company_matching_digest.recipientType,
    'company',
  )
  assert.equal(
    WHATSAPP_AUTOMATION_EVENT_RULES.worker_matching_digest.notificationPurpose,
    'matching',
  )
  assert.equal(
    WHATSAPP_AUTOMATION_EVENT_RULES.worker_payment_or_plan_reminder.notificationPurpose,
    'service',
  )
})

test('72-hour automation cycle windows are deterministic at exact boundaries', () => {
  assert.deepEqual(
    getWhatsappAutomationCycleWindow(new Date('2026-08-25T00:00:00.000Z')),
    {
      cycleStartsAt: '2026-08-23T00:00:00.000Z',
      cycleEndsAt: '2026-08-26T00:00:00.000Z',
    },
  )
  assert.deepEqual(
    getWhatsappAutomationCycleWindow(new Date('2026-08-26T23:59:59.999Z')),
    {
      cycleStartsAt: '2026-08-26T00:00:00.000Z',
      cycleEndsAt: '2026-08-29T00:00:00.000Z',
    },
  )
  assert.deepEqual(
    getWhatsappAutomationCycleWindow(new Date('2026-08-27T00:00:00.000Z')),
    {
      cycleStartsAt: '2026-08-26T00:00:00.000Z',
      cycleEndsAt: '2026-08-29T00:00:00.000Z',
    },
  )
})

